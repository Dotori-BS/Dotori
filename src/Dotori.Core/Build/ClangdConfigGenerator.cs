using System.Diagnostics;
using System.Text;

namespace Dotori.Core.Build;

public static class ClangdConfigGenerator
{
    public static string BuildContent(string compilerPath, string? resourceDir = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Generated by dotori");
        sb.AppendLine("CompileFlags:");
        sb.AppendLine($"  Compiler: {YamlSingleQuoted(compilerPath)}");

        var removeList = new List<string>
        {
            "\"--precompile\"",
            "\"--driver-mode=*\"",
        };
        if (resourceDir is not null)
            removeList.Add("\"-resource-dir=*\"");

        sb.AppendLine($"  Remove: [{string.Join(", ", removeList)}]");

        if (resourceDir is not null)
            sb.AppendLine($"  Add: [{YamlSingleQuoted($"-resource-dir={resourceDir}")}]");

        return sb.ToString();
    }

    public static async Task WriteAsync(string outputPath, string compilerPath, CancellationToken ct = default)
    {
        outputPath = Path.GetFullPath(outputPath);
        var outputDirectory = Path.GetDirectoryName(outputPath)!;
        Directory.CreateDirectory(outputDirectory);
        var resourceDir = DetectResourceDir(compilerPath);
        var tempPath = Path.Combine(outputDirectory, $".{Path.GetFileName(outputPath)}.{Guid.NewGuid():N}.tmp");
        try
        {
            await File.WriteAllTextAsync(tempPath, BuildContent(compilerPath, resourceDir), ct);
            File.Move(tempPath, outputPath, overwrite: true);
        }
        finally
        {
            if (File.Exists(tempPath)) File.Delete(tempPath);
        }
    }

    private static string YamlSingleQuoted(string value) => $"'{value.Replace("'", "''")}'";

    private static string? DetectResourceDir(string compilerPath)
    {
        try
        {
            var psi = new ProcessStartInfo(compilerPath, "-print-resource-dir")
            {
                RedirectStandardOutput = true,
                RedirectStandardError  = true,
                UseShellExecute        = false,
                CreateNoWindow         = true,
            };
            using var proc = Process.Start(psi);
            if (proc is null) return null;
            var output = proc.StandardOutput.ReadToEnd().Trim();
            proc.WaitForExit();
            return proc.ExitCode == 0 && output.Length > 0 ? output : null;
        }
        catch
        {
            return null;
        }
    }
}
